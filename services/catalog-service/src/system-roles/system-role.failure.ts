import { HttpException } from '@nestjs/common';
import type { RoleRunRow } from './system-role.types';

const contextWindow = 'Оценка контекста с резервом для ответа превышает настроенное окно модели. Уменьшите сообщение или начните новый диалог.';
const contextLimits = new Set([
    'Уменьшите выбранный контекст.',
    'Сообщение с содержимым файлов превышает предел 128 КиБ текста.',
    'Контекст превышает предел запроса 8 МиБ. Начните новый диалог.',
    'Выбранный контекст превышает предел цели. Выберите меньший фрагмент.',
    'Общий выбранный контекст больше 64 КиБ. Уменьшите выбор.',
]);
const invalidResults = new Set([
    'Ответ системного агента не прошёл проверку JSON-контракта.',
    'Системный агент не вернул проверяемый результат.',
    'Ответ с источниками превышает предел 32 КиБ.',
    'Ответ делегата превысил предел.',
    'Итоговый ответ превысил предел.',
]);
const truncated = 'Модель остановилась на пределе ответа. Ответ не завершён и не принят; автоматического повтора нет. Уменьшите задачу или выберите модель с большим пределом ответа.';
const featureUnavailable = 'Не удалось проверить доступность функции. Повторите запрос после восстановления сервиса флагов.';
const phases: Record<string, string> = {
    queued: 'ожидание', collecting: 'сбор диагностики', validating_context: 'проверка контекста',
    model_step: 'шаг модели', delegating: 'делегирование', mcp_step: 'шаг инструмента', mcp_unavailable: 'проверка инструментов',
};

/** Classify trusted HTTP errors without publishing arbitrary provider bodies, messages or paths. */
function explanation(cause: unknown): string {
    if (cause instanceof HttpException) {
        const status = cause.getStatus(), response = cause.getResponse();
        if (status === 403 && typeof response === 'object' && response !== null && 'code' in response && response.code === 'feature-disabled') {
            return 'Функция отключена. Включите требуемую функцию в настройках или обратитесь к администратору перед новым явным запуском.';
        }
        if (status === 400 && cause.message === contextWindow) return 'Окно контекста модели по оценке не вмещает выбранные сообщения и резерв ответа. Проверьте настройки окна контекста и предела ответа модели или уменьшите выбранный контекст, затем подготовьте запуск заново.';
        if ((status === 400 || status === 409) && contextLimits.has(cause.message)) return 'Контекст превышает допустимый размер. Уменьшите выбранный текст и источники, затем подготовьте запуск заново.';
        if (status === 409 && cause.message === 'План делегирования не прошёл проверку разрешённых ролей и выбранного контекста.') return 'План координатора не прошёл проверку разрешённых ролей и контекста. Проверьте задачу и выбранную модель перед новым явным запуском.';
        if (status === 409 && invalidResults.has(cause.message)) return 'Ответ модели не прошёл проверку формата или размера и не принят. Проверьте выбранную модель и сузьте задачу перед новым явным запуском.';
        if (status === 409 && cause.message === 'Системный агент выбрал недоступный инструмент или неверные аргументы MCP.') return 'Модель запросила неразрешённый MCP-инструмент или передала некорректные аргументы. Вызов MCP заблокирован. Проверьте выбранные инструменты и аргументы, затем заново подготовьте и подтвердите контекст.';
        if (status === 400 && cause.message === truncated) return 'Ответ модели оборван на пределе ответа и не принят. Уменьшите задачу или проверьте предел ответа выбранной модели перед новым явным запуском.';
        if (status === 503 && cause.message === featureUnavailable) return 'Не удалось проверить доступность функции. Проверьте сервис флагов перед новым явным запуском.';
        if (status === 401) return 'Авторизация не подтверждена. Войдите заново и проверьте доступ к выбранной модели перед новым явным запуском.';
        if (status === 403) return 'Доступ к запуску или выбранным ресурсам запрещён. Проверьте действующие права пользователя, проекта и модели перед новым явным запуском.';
        if (status === 409) return 'Контекст, версия или состояние запуска изменились. Обновите данные, заново подготовьте и подтвердите выбранный контекст.';
        if (status === 400 || status === 413 || status === 422) return 'Параметры запроса отклонены. Проверьте выбранную модель, задачу и размер контекста, затем подготовьте запуск заново.';
        if (status === 429) return 'Лимит или очередь сервиса не позволили завершить запуск. Проверьте доступную квоту и повторите явный запуск позднее.';
        if ([502, 503, 504].includes(status)) return 'Сервис модели или зависимость недоступны либо не ответили вовремя. Проверьте доступность модели, подключение компьютера и состояние сервисов перед новым явным запуском.';
    }
    return 'Причина сбоя не определена. Проверьте состояние выбранной модели и сервисов перед новым явным запуском; результат запроса не подтверждён.';
}

/** Durable reservations describe progress, never proof of provider dispatch, completion or billing. */
export function systemRoleFailureMessage(cause: unknown, current: Pick<RoleRunRow, 'phase' | 'calls_started'>): string {
    const phase = Object.prototype.hasOwnProperty.call(phases, current.phase) ? phases[current.phase] : 'исполнение';
    const progress = current.calls_started === 0 ? 'Сбой до резервирования шага модели.'
        : `Зарезервировано шагов модели: ${current.calls_started}. Счётчик не подтверждает отправку запроса или получение ответа.`;
    return `${explanation(cause)} Этап: ${phase}. ${progress} Автоматического повтора нет.`;
}
