/** Старые мосты могут подтвердить отказ пустым результатом; новые передают только известный код. */
export function workspaceFailureMessage(result: Record<string, unknown>, version: unknown): string {
    const fields = Object.keys(result);
    if (fields.length === 0) {
        return 'Привязка не выполнена. Мост не сообщил причину. Обновите мост и проверьте папку заново.';
    }
    if (
        version !== 1 ||
        fields.length !== 1 ||
        fields[0] !== 'workspaceFailure' ||
        typeof result.workspaceFailure !== 'string' ||
        !Object.prototype.hasOwnProperty.call(WORKSPACE_FAILURE_MESSAGES, result.workspaceFailure)
    ) {
        throw new ConflictException(
            'Отказ привязки может содержать только поддерживаемый код причины. Локальные данные передавать нельзя.',
        );
    }
    return WORKSPACE_FAILURE_MESSAGES[result.workspaceFailure as keyof typeof WORKSPACE_FAILURE_MESSAGES];
}
