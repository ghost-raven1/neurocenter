import { readFileSync } from 'node:fs';
import { afterEach, describe, expect, it, vi } from 'vitest';
import { defaultFeatureFlags, evaluateFeatureFlags, type FeatureFlagKey } from '../../shared/feature-flags.cjs';
import { ModelRuntime } from '../src/models/model-runtime';
import type { ModelsService } from '../src/models/models.service';
import { ProjectEmbeddingRepository } from '../src/models/project-embedding.repository';
import type { IProjectEmbeddingSelection } from '../src/models/project-embedding.types';
import { ModelChatProjectContext } from '../src/model-chat/chat-project-context';
import { SystemRoleTargets } from '../src/system-roles/system-role.targets';
import { SystemRoleRunner } from '../src/system-roles/system-role.runner';
import { SystemRoleService } from '../src/system-roles/system-role.service';
import { roleDefinitionPin } from '../src/system-roles/system-role.definitions';
import { roleResult } from '../src/system-roles/system-role.validation';
import type { RoleDefinition, RoleRunRow } from '../src/system-roles/system-role.types';
import { LEGACY_BASE, legacyAuthorityPort } from './helpers/system-role-rag-legacy-port';

// Generated by actual eacf600 owners in a separate BASE overlay; never synthesize old pins from current definitions.
const legacy = JSON.parse(readFileSync('test/fixtures/system-role-rag-eacf600.json', 'utf8')) as {
    kind: string; base: string; projectSearchAtAdmission: boolean; definitions: Array<{ definition: RoleDefinition; pin: string }>;
    row: RoleRunRow; coordinatorRow: RoleRunRow; packagerRow: RoleRunRow;
};
const answer = { kind: 'diagnosis', summary: 'Обычный ответ по выбранному промпту', findings: [], nextSteps: [], changes: [] };

function fixture(accepted = legacy.row) {
    const row = structuredClone(accepted);
    // Time alone advances at execution: consent/request/model/snapshot stay byte-for-byte from BASE.
    row.lease_until = new Date(Date.now() + 120000).toISOString();
    const port = legacyAuthorityPort(row), flags = Object.fromEntries(Object.keys(defaultFeatureFlags()).map(key => [key, true])) as Record<FeatureFlagKey, boolean>;
    flags.project_search = false;
    const requests = vi.fn(async (url: string | URL | Request) => {
        const address = String(url);
        if (address.endsWith('/internal/feature-flags/evaluated')) return Response.json(evaluateFeatureFlags(flags));
        if (address.includes('/internal/project-rag/search')) return Response.json({ generation: selected.activeGeneration, snapshot: selected.activeSnapshot, sources: [] });
        throw Error('Unexpected controlled legacy fetch: ' + address);
    });
    vi.stubGlobal('fetch', requests); vi.stubEnv('MODEL_CHAT_CONTEXT_WINDOW_TOKENS', '131072');
    const calls: Array<{ endpoint: 'embed' | 'chat'; body: Record<string, unknown> }> = [];
    const responses: string[] = [];
    let beforeResponse = async () => {};
    const local = { infer: async (_model: unknown, endpoint: 'embed' | 'chat', body: Record<string, unknown>) => {
        calls.push({ endpoint, body }); await beforeResponse();
        return endpoint === 'embed' ? { embeddings: [[1, 2, 3]] } : { done_reason: 'stop', message: { role: 'assistant', content: responses.shift() ?? JSON.stringify(answer) } };
    } };
    const runtime = new ModelRuntime(local as never, {} as never), models = port.models as unknown as ModelsService;
    const selected: IProjectEmbeddingSelection = { projectId: port.project.id, revision: 1, dataRevision: 2,
        activeGeneration: 'initial-' + 'b'.repeat(32), activeSnapshot: 'c'.repeat(64), expectedDimension: 3,
        profile: { provider: 'openai', model: 'fixture:embedding', dimension: 3 }, modelPin: 'd'.repeat(64),
        model: { id: 'legacy-embedding', name: 'Embedding', description: '', runtime: 'ollama', model: 'fixture:embedding', capability: 'embedding',
            dimension: 3, manifestSha256: 'e'.repeat(64), source: 'custom', revision: 1, createdAt: '', updatedAt: '' } };
    vi.spyOn(ProjectEmbeddingRepository.prototype, 'read').mockResolvedValue(selected);
    const context = new ModelChatProjectContext(models, runtime), capture = vi.spyOn(context, 'capture'), retrieve = vi.spyOn(context, 'prepare');
    const targets = new SystemRoleTargets(port.policy, port.agents as never, {} as never, {} as never, requests as typeof fetch, undefined, undefined, context);
    const runner = new SystemRoleRunner(port.repository, port.policy, targets, runtime, async () => undefined, undefined, undefined, undefined, context);
    const abort = new AbortController();
    return { ...port, row, flags, requests, calls, runtime, context, capture, retrieve, targets, abort,
        answers(...values: string[]) { responses.push(...values); },
        beforeResponse(work: () => void | Promise<void>) { beforeResponse = async () => { await work(); }; },
        run: () => runner.run(port.req, row, abort.signal) };
}
afterEach(() => { vi.restoreAllMocks(); vi.unstubAllGlobals(); vi.unstubAllEnvs(); });

describe('Authentic eacf600 grantless accepted run compatibility', () => {
    it('uses an old accepted snapshot produced by BASE, rather than a current initial-OFF fixture', () => {
        expect(legacy.kind).toBe('system-role-eacf600-accepted-grantless-v1'); expect(legacy.base).toBe(LEGACY_BASE);
        expect(legacy.projectSearchAtAdmission).toBe(false); expect(legacy.row.snapshot).not.toHaveProperty('projectContext');
        const definition = legacy.definitions.find(item => item.definition.id === legacy.row.agent_id)!;
        expect(legacy.row.request.expectedDefinitionPin).toBe(definition.pin);
        expect(legacy.row.snapshot.definitionPin).toBe(definition.pin);
        expect(legacy.row.request.expectedDefinitionPin).not.toBe(roleDefinitionPin(legacy.row.agent_id));
        expect(legacy.row.request.consentDigest).toBe(legacy.row.snapshot.consentDigest);
    });
    it('passes real current policy checks for the known persisted old contract without changing accepted pins', async () => {
        const f = fixture(), request = structuredClone(f.row.request), snapshot = structuredClone(f.row.snapshot);
        await expect(f.policy.current(f.req, f.row, f.db as never)).resolves.toMatchObject({ id: f.row.request.modelId });
        expect(f.row.request).toEqual(request); expect(f.row.snapshot).toEqual(snapshot);
        expect(f.queries.some(query => query.sql.includes('FROM project_members'))).toBe(true);
        expect(f.queries.some(query => query.sql.includes('FROM system_role_dialog_intents'))).toBe(true);
    });
    it('continues the ordinary answer with the exact old prompt and zero RAG after project search turns ON', async () => {
        const f = fixture(), request = structuredClone(f.row.request), snapshot = structuredClone(f.row.snapshot);
        f.flags.project_search = true;
        await f.run();
        expect(f.row).toMatchObject({ state: 'succeeded', calls_started: 1, result: answer });
        expect(f.calls.map(call => call.endpoint)).toEqual(['chat']);
        expect((f.calls[0].body.messages as Array<{ role: string; content: string }>)[0]).toEqual({ role: 'system',
            content: legacy.definitions.find(item => item.definition.id === f.row.agent_id)!.definition.prompt });
        expect(f.capture).not.toHaveBeenCalled(); expect(f.retrieve).not.toHaveBeenCalled();
        expect(f.requests.mock.calls.some(([url]) => String(url).includes('/internal/project-rag/search'))).toBe(false);
        expect(f.row.request).toEqual(request); expect(f.row.snapshot).toEqual(snapshot);
        expect(f.row.result).not.toHaveProperty('projectContext');
    });
    it('continues the authentic old coordinator with approved child/synthesis prompts and no new RAG grant', async () => {
        const f = fixture(legacy.coordinatorRow), snapshot = structuredClone(f.row.snapshot), request = structuredClone(f.row.request);
        f.flags.project_search = true;
        f.answers(JSON.stringify({ delegations: [{ roleId: 'agent-autoconfigurator', instruction: 'Проверь свой выбранный промпт.',
            targetKeys: [f.row.snapshot.targets[0].key], diagnostics: [] }] }), JSON.stringify(answer), JSON.stringify(answer));
        await f.run();
        expect(f.row).toMatchObject({ state: 'succeeded', calls_started: 3, result: { ...answer,
            delegations: [{ roleId: 'agent-autoconfigurator', state: 'succeeded', result: answer }] } });
        expect(f.calls.map(call => call.endpoint)).toEqual(['chat', 'chat', 'chat']);
        const messages = f.calls.map(call => call.body.messages as Array<{ role: string; content: string }>);
        expect(messages[0][1].content).not.toContain('SELECTED LEGACY AGENT PROMPT');
        expect(messages[1][0].content).toBe(legacy.definitions.find(item => item.definition.id === 'agent-autoconfigurator')!.definition.prompt
            + ' Ответ должен быть коротким: максимум 4096 байт JSON.');
        expect(messages[1][1].content).toContain('SELECTED LEGACY AGENT PROMPT');
        expect(messages[2][0].content).toBe(legacy.definitions.find(item => item.definition.id === 'agent-coordinator')!.definition.prompt
            + ' Сохрани различие ответов и ошибок делегатов. Верни короткую сводку максимум 8192 байта JSON.');
        expect(f.capture).not.toHaveBeenCalled(); expect(f.retrieve).not.toHaveBeenCalled();
        expect(f.requests.mock.calls.some(([url]) => String(url).includes('/internal/project-rag/search'))).toBe(false);
        expect(f.row.request).toEqual(request); expect(f.row.snapshot).toEqual(snapshot);
        expect(f.row.result).not.toHaveProperty('projectContext'); expect(f.row.result!.delegations![0].result).not.toHaveProperty('projectContext');
    });
    it.each(['agent-packager', 'agent-coordinator'] as const)('preserves the authentic old %s diagnosis-only result restriction', id => {
        const accepted = id === 'agent-packager' ? legacy.packagerRow : legacy.coordinatorRow, prepared = structuredClone(accepted.snapshot);
        const definition = legacy.definitions.find(item => item.definition.id === id)!;
        expect(prepared.definitionPin).toBe(definition.pin); expect(accepted.request.expectedDefinitionPin).toBe(definition.pin);
        expect(definition.definition.targets).toContain(prepared.targets[0].kind);
        const proposal = JSON.stringify({ ...answer, kind: 'proposal', changes: [{ targetKey: prepared.targets[0].key,
            replacement: 'Предлагаемый полный новый текст', explanation: 'Корректная структура изменения явно выбранной цели.' }] });
        // Same actual parser/target/payload: only the approved role capability distinguishes these controls.
        const currentProposal = JSON.stringify({...JSON.parse(proposal), answer: 'Полное объяснение предлагаемого изменения выбранной цели. Изменение не применено.'});
        expect(roleResult(currentProposal, { ...prepared, definitionPin: roleDefinitionPin('agent-autoconfigurator') }, [])).toMatchObject({ kind: 'proposal' });
        expect(() => roleResult(proposal, { ...prepared, definitionPin: roleDefinitionPin(id) }, [])).toThrow('JSON-контракта');
        expect(() => roleResult(proposal, prepared, [])).toThrow('JSON-контракта');
        expect(accepted.snapshot).toEqual(prepared);
    });
    it.each(['ACL', 'model', 'source', 'target', 'lease'] as const)('still rejects a late %s change through the actual owner fence', async kind => {
        const f = fixture(); f.flags.project_search = true;
        f.beforeResponse(() => {
            if (kind === 'ACL') f.state.membership = 'Наблюдатель';
            if (kind === 'model') f.modelRow.descriptor.manifestSha256 = 'f'.repeat(64);
            if (kind === 'source') f.state.sourceAccepted = false;
            if (kind === 'target') f.state.targetText = 'CHANGED AFTER PAID RESPONSE';
            if (kind === 'lease') f.state.leaseValid = false;
        });
        await expect(f.run()).rejects.toThrow(kind === 'ACL' ? 'администратор' : kind === 'model' ? 'pin' : kind === 'source' ? 'отменено' : kind === 'target' ? 'контекст изменился' : 'lease');
        expect(f.calls.map(call => call.endpoint)).toEqual(['chat']); expect(f.row.result).toBeNull();
        expect(f.row.calls_started).toBe(1); expect(f.retrieve).not.toHaveBeenCalled();
    });
    it('rejects an unknown purported old definition even in a persisted grantless row', async () => {
        const f = fixture(); f.row.request.expectedDefinitionPin = '0'.repeat(64); f.row.snapshot.definitionPin = '0'.repeat(64);
        await expect(f.policy.current(f.req, f.row, f.db as never)).rejects.toHaveProperty('status', 409);
        await expect(f.run()).rejects.toThrow(); expect(f.calls).toEqual([]);
    });
    it('does not accept an old request pin and digest against a newly prepared current snapshot', async () => {
        const f = fixture(); f.row.snapshot = await f.targets.prepare(f.req, f.row.agent_id, f.row.snapshot.selection);
        expect(f.row.snapshot.definitionPin).toBe(roleDefinitionPin(f.row.agent_id));
        await expect(f.run()).rejects.toThrow(); expect(f.calls).toEqual([]);
    });
    it('keeps new HTTP admissions current-only when a client replays a valid old consent', async () => {
        const f = fixture(), service = new SystemRoleService(f.models as unknown as ModelsService, f.agents as never,
            {} as never, {} as never, f.runtime, {} as never);
        const create = vi.spyOn(service.repository, 'create');
        await expect(service.start(f.req, f.row.agent_id, structuredClone(legacy.row.request))).rejects.toThrow('Подготовьте и подтвердите');
        expect(create).not.toHaveBeenCalled(); expect(f.calls).toEqual([]);
    });
    it('does not let raw HTTP input supply the server-owned accepted snapshot', async () => {
        const f = fixture(), service = new SystemRoleService(f.models as unknown as ModelsService, f.agents as never,
            {} as never, {} as never, f.runtime, {} as never);
        const create = vi.spyOn(service.repository, 'create');
        await expect(service.start(f.req, f.row.agent_id, { ...legacy.row.request, snapshot: legacy.row.snapshot })).rejects.toHaveProperty('status', 400);
        expect(create).not.toHaveBeenCalled(); expect(f.calls).toEqual([]);
    });
});
