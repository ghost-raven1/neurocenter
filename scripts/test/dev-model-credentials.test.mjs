import {test} from 'node:test';
import assert from 'node:assert/strict';
import {mkdtemp,realpath,rm,stat,readFile,writeFile} from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import {prepareDevModelCredentials} from '../workspace/dev-model-credentials.mjs';
import {modelCredentialEnvironmentIdentity} from '../workspace/model-credentials.mjs';

const key=Buffer.alloc(32,9).toString('base64');
const sql=ids=>async query=>query.includes('to_regclass')?'t':JSON.stringify(ids);
async function fixture(t){const root=await realpath(await mkdtemp(path.join(os.tmpdir(),'nc-dev-key-guard-')));t.after(()=>rm(root,{recursive:true,force:true}));return root;}
test('Existing stored credentials block a fresh checkout before key generation',async t=>{
 const root=await fixture(t);await assert.rejects(prepareDevModelCredentials(root,{}, {sql:sql(['a'.repeat(24)])}),/Восстановите исходные/);
 await assert.rejects(stat(path.join(root,'.run')),{code:'ENOENT'});
});
test('Empty database permits one permanent key and repeats with that exact DB identity',async t=>{
 const root=await fixture(t),first=await prepareDevModelCredentials(root,{}, {sql:sql([])}),identity=await modelCredentialEnvironmentIdentity(root,{});
 const second=await prepareDevModelCredentials(root,{}, {sql:sql([identity.keyId])});assert.deepEqual(first,second);
 assert.ok(!JSON.stringify(identity).includes((await readFile(first.NEUROCENTER_MODEL_CREDENTIAL_KEY_FILE,'utf8')).trim()));
});
test('Deleting key and marker together cannot silently rotate over retained database credentials',async t=>{
 const root=await fixture(t);await prepareDevModelCredentials(root,{}, {sql:sql([])});const identity=await modelCredentialEnvironmentIdentity(root,{});
 await rm(path.join(root,'.run/model-credentials'),{recursive:true});
 await assert.rejects(prepareDevModelCredentials(root,{}, {sql:sql([identity.keyId])}),/Восстановите исходные/);
 await assert.rejects(stat(path.join(root,'.run/model-credentials')),{code:'ENOENT'});
});
test('Explicit operator key is validated against DB without creating local key files',async t=>{
 const root=await fixture(t),environment={NEUROCENTER_MODEL_CREDENTIAL_KEY:key},identity=await modelCredentialEnvironmentIdentity(root,environment);
 assert.deepEqual(await prepareDevModelCredentials(root,environment,{sql:sql([identity.keyId])}),environment);
 await assert.rejects(prepareDevModelCredentials(root,environment,{sql:sql(['a'.repeat(24)])}));await assert.rejects(stat(path.join(root,'.run')),{code:'ENOENT'});
});
test('Explicit relative operator file resolves to its verified absolute path for catalog',async t=>{
 const root=await fixture(t);await writeFile(path.join(root,'operator.key'),key+'\n',{mode:0o600});
 const environment={NEUROCENTER_MODEL_CREDENTIAL_KEY_FILE:'operator.key'},identity=await modelCredentialEnvironmentIdentity(root,environment);
 assert.deepEqual(await prepareDevModelCredentials(root,environment,{sql:sql([identity.keyId])}),{NEUROCENTER_MODEL_CREDENTIAL_KEY_FILE:path.join(root,'operator.key')});
});
for(const environment of [{NEUROCENTER_MODEL_CREDENTIAL_KEY:''},{NEUROCENTER_MODEL_CREDENTIAL_KEY:'invalid'},{NEUROCENTER_MODEL_CREDENTIAL_KEY:key+'\n'},{NEUROCENTER_MODEL_CREDENTIAL_KEY_FILE:''},{NEUROCENTER_MODEL_CREDENTIAL_KEY:key,NEUROCENTER_MODEL_CREDENTIAL_KEY_FILE:'operator.key'}])test('Invalid explicit settings cannot bypass validation: '+Object.keys(environment).join('+')+' '+Object.values(environment).map(value=>value.length).join(','),async t=>{
 const root=await fixture(t);await assert.rejects(prepareDevModelCredentials(root,environment,{sql:sql([])}));await assert.rejects(stat(path.join(root,'.run')),{code:'ENOENT'});
});
test('Concurrent database identity change fails closed after generation and preserves generated bytes',async t=>{
 const root=await fixture(t);let reads=0;
 await assert.rejects(prepareDevModelCredentials(root,{}, {sql:async query=>query.includes('to_regclass')?'t':JSON.stringify(++reads===1?[]:['a'.repeat(24)])}),/Восстановите исходные/);
 const filename=path.join(root,'.run/model-credentials/secrets/model_credential_key'),before=await readFile(filename);
 await assert.rejects(prepareDevModelCredentials(root,{}, {sql:sql(['a'.repeat(24)])}));assert.deepEqual(await readFile(filename),before);
});
test('External key replacement during DB check is rejected without overwriting the operator file',async t=>{
 const root=await fixture(t),filename=path.join(root,'operator.key');await writeFile(filename,key+'\n',{mode:0o600});
 const environment={NEUROCENTER_MODEL_CREDENTIAL_KEY_FILE:filename},identity=await modelCredentialEnvironmentIdentity(root,environment);let reads=0;
 await assert.rejects(prepareDevModelCredentials(root,environment,{sql:async query=>{if(query.includes('to_regclass'))return 't';if(++reads===2)await writeFile(filename,Buffer.alloc(32,10).toString('base64')+'\n');return JSON.stringify([identity.keyId]);}}));
 assert.notEqual((await readFile(filename,'utf8')).trim(),key);await assert.rejects(stat(path.join(root,'.run')),{code:'ENOENT'});
});
test('Database errors are sanitized and prevent any key generation',async t=>{
 const root=await fixture(t);await assert.rejects(prepareDevModelCredentials(root,{}, {sql:async()=>{throw Error('private database details');}}),error=>!error.message.includes('private'));
 await assert.rejects(stat(path.join(root,'.run')),{code:'ENOENT'});
});
