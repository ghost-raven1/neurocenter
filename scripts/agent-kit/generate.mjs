import fs from 'node:fs/promises';
import path from 'node:path';
import {createHash} from 'node:crypto';
import {fileURLToPath,pathToFileURL} from 'node:url';

export const KIT_VERSION='0.1.2';
export const repositoryRoot=fileURLToPath(new URL('../../',import.meta.url));
const groups={product:'Задача и продукт',frontend:'Фронтенд',backend:'Бэкенд',models:'Модели и агенты',knowledge:'Знания и хранение',delivery:'Сборка и поставка',quality:'Качество',operations:'Эксплуатация'};
const core='.opencode/skills/neurocenter-task-flow';
const commonFiles=['SKILL.md','agents/openai.yaml','references/interface.md','references/roles.md','references/verification.md','references/neurocenter.md','references/development-debugging.md','references/codex.md','references/opencode.md'];
const marker='Generated by scripts/agent-kit/generate.mjs';
const sha=value=>createHash('sha256').update(value).digest('hex');
const bullets=values=>values.map(value=>'- '+value).join('\n');
const text=value=>typeof value==='string'&&value.length>0&&value.length<=700&&!/[\x00-\x1f\x7f]/.test(value);
const optionalRead=async file=>{
    const absolute=path.resolve(file);let missing=false;
    for(let current=absolute;current!==path.dirname(current);current=path.dirname(current)){
        try{const stat=await fs.lstat(current);if(stat.isSymbolicLink()||(current===absolute?!stat.isFile():!stat.isDirectory()))throw Error('Небезопасный путь набора: '+current);}
        catch(error){if(error.code!=='ENOENT')throw error;if(current===absolute)missing=true;}
    }
    return missing?null:fs.readFile(absolute);
};

/** Validate the exact 8x8 role catalogue before generating any project files. */
export async function loadRoles(root=repositoryRoot){
    const roles=[];
    for(const group of Object.keys(groups)){
        const entries=JSON.parse(await fs.readFile(path.join(root,'scripts/agent-kit/roles',group+'.json'),'utf8'));
        if(!Array.isArray(entries)||entries.length!==8)throw Error('Нужно восемь ролей группы '+group);
        for(const role of entries){
            if(!role||!/^[a-z][a-z0-9-]{1,47}$/.test(role.id)||role.group!==group||!['read','write','coordinate'].includes(role.mode)
                ||!['title','focus','outcome'].every(key=>text(role[key]))||role.focus.length>220
                ||!['inputs','checks','boundaries'].every(key=>Array.isArray(role[key])&&role[key].length>=1&&role[key].length<=4&&role[key].every(text)))throw Error('Некорректный профиль роли: '+String(role?.id));
            roles.push(role);
        }
    }
    if(roles.length!==64||new Set(roles.map(role=>role.id)).size!==64)throw Error('Нужны ровно 64 уникальные роли.');
    return roles;
}

function skill(role){
    return `---\nname: neurocenter-${role.id}\ndescription: ${JSON.stringify(role.focus)}\nmetadata:\n  version: "${KIT_VERSION}"\n---\n\n<!-- ${marker}; edit scripts/agent-kit/roles/${role.group}.json. -->\n\n# ${role.title}\n\nПрименяй [общий workflow](../neurocenter-task-flow/SKILL.md) в объёме переданной задачи.\n\nОжидаемый результат: ${role.outcome}\n\n## Вход\n\n${bullets(role.inputs)}\n\n## Профильные проверки\n\n${bullets(role.checks)}\n\n## Границы\n\n${bullets(role.boundaries)}\n${role.mode==='read'?'\nЭто исследование/review: используй доступное read-only чтение, diff, историю и хеши. Не меняй файлы, не запускай тесты, сборки и сервисы; необходимые запуски передай основному агенту.\n':''}`;
}

function codex(role){
    const scope=role.mode==='read'?'Use read-only file inspection, diff, history and hashes as available. Do not edit files, run tests/builds/services or use tools with side effects. Ask the primary agent to perform any necessary execution.':'Keep changes within the assigned files and user-authorized task. Preserve existing data and configuration; do not infer permission for deployment, account changes or paid requests.';
    return `# ${marker}; edit roles/${role.group}.json.\nname = "neurocenter-${role.id}"\ndescription = ${JSON.stringify(role.focus)}\ndeveloper_instructions = ${JSON.stringify(`Use the installed skill neurocenter-${role.id} and its shared neurocenter-task-flow instructions. Deliver: ${role.outcome}\n${scope}\nReport evidence and unresolved limits to the primary agent.`)}\n`;
}

function opencode(role){
    return `---\ndescription: ${JSON.stringify(role.focus)}\nmode: ${role.id==='task-orchestrator'?'primary':'subagent'}\n${role.mode==='read'?'permission:\n  edit: deny\n  bash: deny\n  task: deny\n':''}---\n\n<!-- ${marker}; edit roles/${role.group}.json. -->\n\nПрочитай \`.opencode/skills/neurocenter-${role.id}/SKILL.md\` и выполни профиль по переданной задаче.\n\n${role.mode==='read'?'Используй доступные средства чтения. Не меняй файлы и не вызывай MCP с побочными эффектами. Необходимые команды передай основному агенту.':'Сохраняй авторизованный объём и владельцев файлов; итог и проверки передай основному агенту.'}\n`;
}

/** Render provider-specific adapters from one role definition; detailed skills stay on demand. */
export function renderRoles(roles){
    const files=new Map();
    for(const role of roles){
        files.set(`.opencode/skills/neurocenter-${role.id}/SKILL.md`,skill(role));
        files.set(`.opencode/agents/neurocenter-${role.id}.md`,opencode(role));
        files.set(`scripts/agent-kit/codex/neurocenter-${role.id}.toml`,codex(role));
    }
    const menu=['# Каталог 64 ролей','',`<!-- ${marker}. -->`,'','Выбери специалистов по реальной задаче. Подробности skill загружай только для выбранных ролей; число одновременно запущенных агентов ограничивает текущая среда.',''];
    for(const [group,title]of Object.entries(groups)){
        menu.push('## '+title,'','| Роль | Задача |','| --- | --- |');
        for(const role of roles.filter(role=>role.group===group))menu.push(`| [${role.title}](../../neurocenter-${role.id}/SKILL.md) | ${role.focus} |`);
        menu.push('');
    }
    files.set(core+'/references/catalog.md',menu.join('\n'));
    return files;
}

/** Refuse to replace a modified generated file; --check never writes. */
export async function generateKit({root=repositoryRoot,checkOnly=false}={}){
    const roles=await loadRoles(root),outputs=renderRoles(roles),manifestPath=path.join(root,'scripts/agent-kit/manifest.json');
    const oldRaw=await optionalRead(manifestPath),old=oldRaw?JSON.parse(oldRaw):null,plan=[],hashes={};
    for(const [relative,content]of outputs){
        const current=await optionalRead(path.join(root,relative)),desired=Buffer.from(content),currentHash=current&&sha(current);
        if(current&&!current.equals(desired)&&old?.files?.[relative]!==currentHash)throw Error('Сохранён изменённый файл; разберите конфликт: '+relative);
        plan.push({relative,desired,before:currentHash,changed:!current?.equals(desired)});hashes[relative]=sha(desired);
    }
    for(const relative of [...commonFiles.map(name=>core+'/'+name),'.opencode/commands/neurocenter-task.md']){
        const current=await optionalRead(path.join(root,relative));if(!current)throw Error('Нет общего файла '+relative);hashes[relative]=sha(current);
    }
    const manifest=JSON.stringify({schemaVersion:1,version:KIT_VERSION,roleCount:roles.length,files:Object.fromEntries(Object.entries(hashes).sort())},null,2)+'\n';
    const changed=plan.filter(item=>item.changed).map(item=>item.relative);if(oldRaw?.toString()!==manifest)changed.push('scripts/agent-kit/manifest.json');
    if(!checkOnly){
        for(const item of plan.filter(item=>item.changed)){
            const file=path.join(root,item.relative),current=await optionalRead(file);
            if((current&&sha(current))!==item.before)throw Error('Файл изменился во время генерации: '+item.relative);
            await fs.mkdir(path.dirname(file),{recursive:true});await fs.writeFile(file,item.desired,{flag:current?'w':'wx'});
        }
        await fs.mkdir(path.dirname(manifestPath),{recursive:true});await fs.writeFile(manifestPath,manifest);
    }
    return {version:KIT_VERSION,roles:roles.length,skills:roles.length+1,generatedFiles:outputs.size,checkedFiles:Object.keys(hashes).length,checkOnly,changed};
}

if(process.argv[1]&&import.meta.url===pathToFileURL(path.resolve(process.argv[1])).href){
    const args=process.argv.slice(2);if(args.some(arg=>arg!=='--check'))throw Error('Используйте generate.mjs [--check]');
    const result=await generateKit({checkOnly:args.includes('--check')});console.log(JSON.stringify(result));if(result.checkOnly&&result.changed.length)process.exitCode=1;
}
